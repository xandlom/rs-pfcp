//! Robustness: every IE parser must return `Err`/`Ok`, never panic, on
//! truncated or flag-permuted input (Phase 2 of the remediation plan).
//!
//! The parser list is generated from the `pub fn unmarshal(&[u8])` entry points
//! in `src/ie/`; `every_ie_module_is_registered` fails if a new IE file is added
//! without being listed here.

use std::panic::{catch_unwind, AssertUnwindSafe};

type Parser = (&'static str, fn(&[u8]));

macro_rules! parsers {
    ($($m:ident :: $t:ident),* $(,)?) => {
        &[$((concat!(stringify!($m), "::", stringify!($t)), |d: &[u8]| {
            let _ = rs_pfcp::ie::$m::$t::unmarshal(d);
        })),*]
    };
}

