/// Every octet-length up to this is tried for every input shape.
const MAX_LEN: usize = 40;

#[test]
fn ie_parsers_never_panic_on_truncated_or_flag_permuted_input() {
    let prev = std::panic::take_hook();
    std::panic::set_hook(Box::new(|_| {}));

    let mut failures: Vec<String> = Vec::new();
    for (name, parse) in PARSERS {
        'outer: for first in 0..=255u8 {
            for fill in [0x00u8, 0xFF, 0x5A] {
                for len in 0..=MAX_LEN {
                    let mut buf = vec![fill; len];
                    if let Some(b) = buf.first_mut() {
                        *b = first;
                    }
                    if catch_unwind(AssertUnwindSafe(|| parse(&buf))).is_err() {
                        failures.push(format!("{name}: panic on {buf:02x?}"));
                        break 'outer;
                    }
                }
            }
        }
    }

    std::panic::set_hook(prev);
    assert!(
        failures.is_empty(),
        "{} IE parser(s) panicked:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn every_ie_module_is_registered() {
    let src =
        std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/src/ie/mod.rs")).unwrap();
    let registered = include_str!("ie_truncation.rs");
    let missing: Vec<_> = src
        .lines()
        .filter_map(|l| l.strip_prefix("pub mod ")?.strip_suffix(';'))
        .filter(|m| !matches!(*m, "builder_support"))
        .filter(|m| !registered.contains(&format!("    {m}::")))
        .map(str::to_owned)
        .collect();
    assert!(
        missing.is_empty(),
        "IE modules missing from PARSERS: {missing:?}"
    );
}
